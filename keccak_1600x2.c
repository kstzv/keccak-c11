    s[6][1] = rotl64(s[6][1], 44);
    
    s[7][0] = rotl64(s[7][0], 6);
    s[7][1] = rotl64(s[7][1], 6);
    
    s[8][0] = rotl64(s[8][0], 55);
    s[8][1] = rotl64(s[8][1], 55);
    
    s[9][0] = rotl64(s[9][0], 20);
    s[9][1] = rotl64(s[9][1], 20);
    

    s[10][0] = rotl64(s[10][0], 3);
    s[10][1] = rotl64(s[10][1], 3);
    
    s[11][0] = rotl64(s[11][0], 10);
    s[11][1] = rotl64(s[11][1], 10);
    
    s[12][0] = rotl64(s[12][0], 43);
    s[12][1] = rotl64(s[12][1], 43);
    
    s[13][0] = rotl64(s[13][0], 25);
    s[13][1] = rotl64(s[13][1], 25);
    
    s[14][0] = rotl64(s[14][0], 39);
    s[14][1] = rotl64(s[14][1], 39);
    

    s[15][0] = rotl64(s[15][0], 41);
    s[15][1] = rotl64(s[15][1], 41);
    
    s[16][0] = rotl64(s[16][0], 45);
