static inline uint64_t rotl64(uint64_t x, unsigned n)
{
    return (x << n) | (x >> (64 - n));
}

static inline void keccak_theta(uint64_t s[25][4]);
static inline void keccak_rho(uint64_t s[25][4]);
static inline void keccak_pi(uint64_t s[25][4]);
