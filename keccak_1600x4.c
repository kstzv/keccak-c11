static inline void keccak_iota(uint64_t s[25][4], unsigned round);

static void keccak_f1600_x4(uint64_t s[25][4])
{
    for (unsigned round = 0; round < 24; round++) 
    {
        keccak_theta(s);
        keccak_rho(s);
        keccak_pi(s);
        keccak_chi(s);
        keccak_iota(s, round);
    }
}

